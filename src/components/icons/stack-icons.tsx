export function StackIcon({
  name,
  className,
}: {
  name: IconKey;
  className?: string;
}): JSX.Element {
  const Icon: IconType = stackIcons[name];
  const color: string | undefined = stackIconColors[name];
  return (
    <Icon
      aria-hidden="true"
      className={className}
      {...(color ? { color } : {})}
    />
  );
}
